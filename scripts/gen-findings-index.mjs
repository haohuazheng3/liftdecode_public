// Generates src/content/findings/index.ts from the finding files in that folder.
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
const dir = join(process.cwd(), "src/content/findings");
const files = readdirSync(dir).filter((f) => f.endsWith(".ts") && f !== "index.ts").sort();
const ids = files.map((f) => f.replace(/\.ts$/, ""));
const imports = ids.map((id, i) => `import { FINDING as f${i} } from "./${id}";`).join("\n");
const entries = ids.map((id, i) => `  ["${id}"]: f${i},`).join("\n");
const out = `// AUTO-GENERATED by scripts/gen-findings-index.mjs — do not edit by hand.
import type { FindingContent } from "../types";
${imports}

export const FINDINGS: Record<string, FindingContent> = {
${entries}
};

export const FINDING_LIST: FindingContent[] = Object.values(FINDINGS);
`;
writeFileSync(join(dir, "index.ts"), out);
console.log(`findings index: ${ids.length} entries`);
